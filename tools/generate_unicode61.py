#!/usr/bin/env python3
"""Regenerate unicode61_data.rs from SQLite's public FTS5 vocabulary interface.

Run with Python linked to an FTS5-enabled SQLite. Each input row contains one
Unicode scalar and uses its code point as the rowid. No SQLite source tables
or private interfaces are used. The resulting lookup tables have no runtime
SQLite dependency.
"""
import sqlite3
from pathlib import Path

CATEGORIES = "Cc Cf Cn Co Cs Ll Lm Lo Lt Lu Mc Me Mn Nd Nl No Pc Pd Pe Pf Pi Po Ps Sc Sk Sm So Zl Zp Zs".split()
SCALARS = 0x110000
OUTPUT = Path(__file__).resolve().parents[1] / "crates/fsqlite-ext-fts5/src/unicode61_data.rs"


def observed_rows(categories, mode, changes_only=False):
    connection = sqlite3.connect(":memory:")
    try:
        connection.execute(
            f"""CREATE VIRTUAL TABLE words USING fts5(body, content='',
                tokenize="unicode61 categories '{categories}' remove_diacritics {mode}")"""
        )
        connection.execute("CREATE VIRTUAL TABLE vocab USING fts5vocab(words, 'instance')")
        query = "SELECT doc, term FROM vocab"
        if changes_only:
            query += " WHERE term IS NOT char(doc)"
        for start in range(0, SCALARS, 16384):
            connection.execute("""
                WITH RECURSIVE codes(i) AS (
                    VALUES(?) UNION ALL SELECT i+1 FROM codes WHERE i+1 < ?
                ) INSERT INTO words(rowid, body)
                SELECT i, char(i) FROM codes WHERE i NOT BETWEEN 55296 AND 57343
            """, (start, min(start + 16384, SCALARS)))
            yield from connection.execute(query)
            connection.execute("INSERT INTO words(words) VALUES ('delete-all')")
    finally:
        connection.close()


def rust_array(name, ty, entries, per_line):
    entries = list(entries)
    lines = ["#[rustfmt::skip]", f"static {name}: &[{ty}] = &["]
    for i in range(0, len(entries), per_line):
        lines.append("    " + ", ".join(entries[i:i + per_line]) + ",")
    return "\n".join([*lines, "];", ""])


def generate():
    # Five observations distinguish the 30 real categories. Scalars accepted
    # for every nonempty selection get code 31, those accepted for none get 0.
    category = bytearray(SCALARS)
    for bit in range(5):
        names = " ".join(n for i, n in enumerate(CATEGORIES, 1) if i & (1 << bit))
        for cp, _ in observed_rows(names, 0):
            category[cp] |= 1 << bit
    starts = [(cp << 5) | code for cp, code in enumerate(category)
              if cp == 0 or code != category[cp - 1]]

    # Start with case folding. Diacritic overrides contain only the extra
    # changes from the preceding mode, keyed by the original scalar.
    mappings = []
    for mode in range(3):
        result = {}
        for cp, term in observed_rows("L* M* N* P* S* Z* C*", mode, True):
            if term is not None and len(term) == 1:
                result[cp] = ord(term)
            elif term not in ("", None):
                raise ValueError(f"unexpected unicode61 expansion U+{cp:04X}: {term!r}")
        mappings.append(result)
    case_fold, mode_one, mode_two = mappings
    def differences(before, after):
        return {cp: after.get(cp, cp) for cp in before.keys() | after.keys()
                if before.get(cp, cp) != after.get(cp, cp)}
    simple = differences(case_fold, mode_one)
    full = differences(mode_one, mode_two)
    def pairs(name, mapping):
        return rust_array(name, "(u32, u32)", (f"(0x{k:x}, 0x{v:x})" for k, v in sorted(mapping.items())), 4)
    names = ", ".join(f'"{n}"' for n in CATEGORIES)
    return (
        "// Generated by tools/generate_unicode61.py using SQLite's FTS5 interface.\n"
        "// Each category range packs its start code point above a five-bit category.\n"
        f"#[rustfmt::skip]\npub(super) const CATEGORY_NAMES: [&str; 30] = [{names}];\n\n"
        + rust_array("CATEGORIES", "u32", (hex(n) for n in starts), 8)
        + pairs("FOLD", case_fold) + pairs("SIMPLE", simple) + pairs("FULL_EXTRA", full)
        + '''
pub(super) fn category(ch: char) -> u32 {
    let cp = u32::from(ch);
    let end = CATEGORIES.partition_point(|entry| entry >> 5 <= cp);
    CATEGORIES[end - 1] & 31
}

fn mapped(mapping: &[(u32, u32)], cp: u32) -> Option<u32> {
    mapping
        .binary_search_by_key(&cp, |entry| entry.0)
        .ok()
        .map(|i| mapping[i].1)
}

pub(super) fn fold(ch: char, remove_diacritics: u8) -> char {
    if ch.is_ascii() {
        return ch.to_ascii_lowercase();
    }
    let cp = u32::from(ch);
    let replacement = match remove_diacritics {
        0 => None,
        2 => mapped(FULL_EXTRA, cp).or_else(|| mapped(SIMPLE, cp)),
        _ => mapped(SIMPLE, cp),
    };
    replacement
        .or_else(|| mapped(FOLD, cp))
        .and_then(char::from_u32)
        .unwrap_or(ch)
}
'''
    )


if __name__ == "__main__":
    OUTPUT.write_text(generate(), encoding="utf-8")
